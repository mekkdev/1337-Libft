#include <stdio.h>

void	*memset(void *b, int c, size_t n)
{
	size_t	i;
	char	*ptr;

	ptr = b;
	i = 0;
	while (i < n)
	{
		ptr[i] = c;
		i++;
	}
	return (b);
}
